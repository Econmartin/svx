import * as React from 'react';
import { cn } from '@/lib/cn';

export const Card = React.forwardRef<HTMLDivElement, React.HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        'rounded-2xl border border-border bg-surface/75 text-white shadow-card backdrop-blur-xl',
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = 'Card';

export const CardHeader = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn('flex flex-col space-y-1.5 px-6 pt-5 pb-3', className)}
    {...props}
  />
));
CardHeader.displayName = 'CardHeader';

// Card titles are semantic h3 — gives every page a real h1→h3 hierarchy
// instead of div-only "titles" that fail screen-reader landmarking. Size
// bumped to sm/15px with semibold + tight tracking to read as a real
// section header against the long body copy that follows.
export const CardTitle = React.forwardRef<
  HTMLHeadingElement,
  React.HTMLAttributes<HTMLHeadingElement>
>(({ className, ...props }, ref) => (
  <h3
    ref={ref}
    className={cn(
      'text-[17px] text-fg font-semibold tracking-[-0.018em] leading-snug',
      className,
    )}
    {...props}
  />
));
CardTitle.displayName = 'CardTitle';

